(async () => {
  const checks = [], samples = [];
  const check = (ok, name) => { if (!ok) throw Error(name); checks.push(name); };
  const tap = key => {
    window.dispatchEvent(new KeyboardEvent('keydown', { key }));
    window.dispatchEvent(new KeyboardEvent('keyup', { key }));
  };
  const move = pos => {
    P.pos.copy(pos); P.vel.set(0, 0, 0); P.swim = false; P.gehDive = null;
    P.climb = null; P.grounded = true; P.inv = 999; P.dead = false;
    P.lying = false; inputLock = false; sleepT = 0;
    visY = P.pos.y; lastSafePos.copy(P.pos);
  };
  const sample = label => {
    const values = [...camera.position.toArray(), ...camera.quaternion.toArray(), camera.fov, camDist, camYaw, camPitch];
    if (!values.every(Number.isFinite)) throw Error('Nonfinite camera: ' + label);
    if (!(camera.fov > 0 && camera.fov < 180 && camDist > 0)) throw Error('Invalid camera lens/arm: ' + label);
    samples.push({ label, fov: camera.fov, arm: camDist, distance: camera.position.distanceTo(P.pos) });
  };
  const frames = (label, count) => { for (let i = 0; i < count; i++) { update(1 / 60); sample(label); } };
  check(started && !gameplayOverlayOpen(), 'Game is playing with controls available');
  paused = false; WORLDSTATE.afterlife = null;
  for (const k in keys) keys[k] = false;
  const initialYaw = camYaw, initialPitch = camPitch;
  tap('ArrowLeft'); check(Math.abs(camYaw - initialYaw - 0.35) < 1e-9, 'Left arrow retains original +0.35 yaw');
  tap('ArrowRight'); check(Math.abs(camYaw - initialYaw) < 1e-9, 'Right arrow retains original -0.35 yaw');
  tap('ArrowUp'); check(Math.abs(camPitch - initialPitch + 0.2) < 1e-9, 'Up arrow retains original -0.2 pitch');
  tap('ArrowDown'); check(Math.abs(camPitch - initialPitch) < 1e-9, 'Down arrow retains original +0.2 pitch');
  for (let i = 0; i < 20; i++) tap('ArrowUp');
  check(camPitch === -1.2, 'Original lower pitch limit is -1.2');
  for (let i = 0; i < 20; i++) tap('ArrowDown');
  check(camPitch === 1.5, 'Original upper pitch limit is 1.5');
  camPitch = 0.4; camYaw = 0;
  move(V3(90, terrainH(90, 90), 90));
  frames('valley idle', 120);
  const idleFov = camera.fov;
  keys.w = true; keys.shift = true;
  frames('valley run', 120);
  keys.w = false; keys.shift = false;
  const runningFov = camera.fov;
  check(runningFov > idleFov + 0.5, 'Field of view still increases with player speed: ' + JSON.stringify({ idleFov, runningFov, pos: P.pos.toArray(), vel: P.vel.toArray(), moving: P.moving, run: P.run, room: !!roomNow, inputLock, overlay: gameplayOverlayOpen() }));
  const silhouetteCount = root => { let meshes = 0, enabled = 0; root.traverse(o => { if (o.isMesh) { meshes++; if (o.layers.mask & 4) enabled++; } }); return { meshes, enabled }; };
  let local = silhouetteCount(hero);
  check(local.meshes > 0 && local.enabled === local.meshes, 'All local hero meshes support the occlusion silhouette');
  netAddAvatar('qa-camera-peer', netLook(), null, 4, 4);
  let remote = silhouetteCount(NET.avatars.get('qa-camera-peer').mesh);
  check(remote.meshes > 0 && remote.enabled === 0, 'Remote avatar creation does not enable the local silhouette layer');
  netAddAvatar('qa-camera-peer', netLook(), null, 4, 4);
  remote = silhouetteCount(NET.avatars.get('qa-camera-peer').mesh);
  check(remote.enabled === 0, 'Remote appearance rebuild also excludes the silhouette layer');
  rebuildHero(); local = silhouetteCount(hero);
  check(local.meshes === local.enabled, 'Local appearance rebuild preserves its silhouette');
  let foreignSilhouetteMeshes = 0;
  scene.traverse(o => { if (!o.isMesh || !(o.layers.mask & 4)) return; let p = o; while (p && p !== hero) p = p.parent; if (!p) foreignSilhouetteMeshes++; });
  check(foreignSilhouetteMeshes === 0, 'Silhouette render layer contains only the local hero');
  netRemoveAvatar('qa-camera-peer');
  paused = true;
  GEH.seed = 4321;
  await window.gehBuildWorld();
  WORLDSTATE.gehDone = true; WORLDSTATE.luciferDefeated = true;
  GEH.inPride = false; GEH.kingdom.cooldown = 0; GEH.kingdom.transit = null;
  move(GEH.kingdom.portal.clone());
  camYaw = 1.123; camPitch = -0.321; P.heading = 2.345;
  const angle = () => [camYaw, camPitch, P.heading];
  const beforeEnter = angle();
  gehUpdateKingdom(0.25);
  check(GEH.inPride && GEH.kingdom.transit.moved, 'Portal enters Pride in the real game closure');
  check(angle().every((v, i) => v === beforeEnter[i]), 'Pride entry preserves yaw, pitch, and heading exactly');
  gehUpdateKingdom(1); GEH.kingdom.cooldown = 0;
  paused = false; frames('Pride', 120);
  paused = true;
  move(V3(GEH.cx - 85, GEH.kingdom.y + 0.05, GEH.cz + 40.5));
  camYaw = -0.987; camPitch = 0.654; P.heading = -2.123;
  const beforeLeave = angle();
  gehUpdateKingdom(0.25);
  check(!GEH.inPride && GEH.kingdom.transit.moved, 'Portal returns to the Still Kingdom');
  check(angle().every((v, i) => v === beforeLeave[i]), 'Pride exit preserves yaw, pitch, and heading exactly');
  gehUpdateKingdom(1); paused = false;
  frames('kingdom', 120);
  check(camera.position.distanceTo(P.pos) < 30, 'Restored controller settles near the player after portal transit');
  paused = true;
  return { checks, total: checks.length, cameraSamples: samples.length, idleFov, runningFov, localMeshes: local.meshes, remoteMeshes: remote.meshes,
    sampleBounds: { minFov: Math.min(...samples.map(s => s.fov)), maxFov: Math.max(...samples.map(s => s.fov)), minArm: Math.min(...samples.map(s => s.arm)), maxArm: Math.max(...samples.map(s => s.arm)) } };
})()
