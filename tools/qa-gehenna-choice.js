  WORLDSTATE.gehUnlocked = true; WORLDSTATE.luciferDefeated = false; WORLDSTATE.gehFinaleWitnessed = false; WORLDSTATE.afterlife = null;
  WORLDSTATE.gehAlmonerDown = WORLDSTATE.gehMatronDown = WORLDSTATE.gehHeapDown = WORLDSTATE.gehDone = false;
