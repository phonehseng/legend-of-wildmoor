    check(matron.state === 'round' && matron.guard === 1 && matron.roundTgt === residents[0], 'Matron immediately leaves her guard to comfort the first awakened person');
    const hp = matron.hp;
    damageEnemy(matron, 10, P.pos, 0, true); gehUpdateMatron(matron, P, -2, 0, 2, 0.05);
    check(matron.hp === hp - 10 && matron.state === 'round', 'full-damage comfort window survives a heavy hit');
    const cadence = matron.roundT;
    damageEnemy(residents[1], 99, P.pos, 0, true);
    check(matron.roundT === cadence && GEH.woken === 2, 'later wakes cannot reset the comfort cadence');

    WORLDSTATE.gehMatronDown = WORLDSTATE.gehHeapDown = true;
    move(GEH.clerkPos.clone());
    for (let i = 0; i < 3; i++) GEH_SCRIPT.interact();
    const kindly = GEH.enemies.find(e => e.kind === 'kindly');
    check(!!kindly, 'Clerk summons the Kindly One through normal dialogue');
    move(kindly.pos.clone()); GEH_SCRIPT.interact(); GEH_SCRIPT.interact();
    check(GEH_SCRIPT.fight, 'Kindly dialogue authorizes her encounter');
    kindly.state = 'windup'; kindly.t = 0.6;
    let before = kindly.hp; damageEnemy(kindly, 10, P.pos, 0, true);
    check(kindly.hp === before - 4 && kindly.state === 'windup', 'raised shears guard against damage and commit to the swing');
    kindly.state = 'strike'; before = kindly.hp; damageEnemy(kindly, 10, P.pos, 0, true);
    check(kindly.hp === before - 4 && kindly.state === 'strike', 'heavy blows cannot cancel the Kindly strike');
    kindly.state = 'recover'; before = kindly.hp; damageEnemy(kindly, 10, P.pos, 0, false);
    check(kindly.hp === before - 10, 'lowered shears expose a full-damage recovery window');
    const playerHp = P.hp, playerGuard = P.bonus.guard;
    P.hp = 0.2; P.inv = 0; P.dodge = 0; P.block = false; P.bonus.guard = 1; death = null;
    time += 10; gehKindlyHit(5, kindly.pos);
    check(P.hp === 0.2 && !death && threadHits === 1, 'Kindly takes a thread while preserving the last health after difficulty scaling');
    P.inv = 0.3; P.dodge = 0.3;
    const cut = threadHits; time += 10; gehKindlyHit(5, kindly.pos);
    check(threadHits === cut, 'a dodged Kindly hit cannot take a thread');
    P.inv = P.dodge = 0; P.block = true;
    const blocks = P.blocks || 0; enemyStrike(kindly, 5, P, 0.7);
    check((P.blocks || 0) === blocks + 1 && P.hp === 0.2 && threadHits === cut, 'a shield stops both Kindly damage and the thread cut');
    P.hp = playerHp; P.bonus.guard = playerGuard; P.inv = 0; P.block = false;

    WORLDSTATE.gehDone = true; GEH.inPride = true; GEH.prideRoom.visible = true; GEH.kingdomRoot.visible = false;
    const e = GEH.lucifer; move(e.pos.clone().add(V3(0, 0, -3)));
    const health = P.hp, position = P.pos.clone(), level = heroLevel(), kills = P.kills;
    gehUpdateFinale(0.05);
    check(e.bodyScale === 0.62 && !e.armed && e.alive && GEH.prideChildren.every(c => c.visible), 'Lucifer begins human-sized beside children with their own activities');
    check(!GEH.prideShelter && GEH.prideChildren[1].scale.y === 0.72, 'children have no cage or tethers and one already chooses to rest');
    for (let i = 0; i < 5; i++) check(gehInteractLucifer(), 'Lucifer introduction ' + (i + 1));
    check(speech.length === 5 && speech.every(c => c.actor.pitch === 1.02 && c.actor.rate === 0.94), 'all five Lucifer lines request his configured voice');
    check(speech[1].line.includes('Ysolde') && !/reborn|never existed/.test(speech[1].line), 'Ysolde absence is quiet and unresolved');
    const advance = seconds => { for (let i = 0; i < Math.ceil(seconds / 0.05); i++) { time += 0.05; gehUpdateLucifer(e, P, 0, 0, 0, 0.05); gehUpdateFinale(0.05); } };
    for (let i = 0; i < 500 && !e.armed; i++) advance(0.05);
    check(e.armed && e.scenePhase === 'hold' && e.bodyScale > 2.39 && GEH.godHand.visible, 'Lucifer runs and grows beneath the arriving hand');
    const heights = [e.bodyScale], childLines = [];
    for (let phase = 1; phase <= 3; phase++) {
      damageEnemy(e, 999, P.pos, 0, true);
      childLines.push(document.querySelector('#subs').lastElementChild.textContent);
      check(e.phase === phase && e.hp === 90 - phase * 30 && e.holdPause > 0, 'overpowered hit stops at child phase ' + phase);
      damageEnemy(e, 999, P.pos, 0, true);
      check(e.phase === phase && e.hp === 90 - phase * 30, 'repeated hit cannot skip child phase ' + phase);
      const childBefore = GEH.prideChildren[0].position.clone();
      advance(2);
      heights.push(e.bodyScale);
      check(e.bodyScale < heights[phase - 1] - 0.4, 'phase ' + phase + ' weakens his hold on the arriving hand');
      check(GEH.prideChildren[0].position.distanceTo(childBefore) > 0.05 && GEH.prideChildren.every(c => c.visible), 'child activities continue during phase ' + phase);
      check(!WORLDSTATE.luciferDefeated && !AFTERLIFE.phase, 'child ' + phase + ' is heard before release');
      for (let i = 0; i < 320 && e.holdPause > 0; i++) advance(0.05);
      check(speech.some(c => c.line === LUCIFER_ANSWERS[phase - 1]), 'Lucifer answers child phase ' + phase);
    }
    check(childLines.every((s, i) => s.includes(LUCIFER_CHILDREN[i])), 'all three children make their own requested choices');
    check(speech.some(c => c.line === 'I was going to choose for everyone. I had not asked anyone.'), 'surrender admits a future plan that never took effect');
    check(WORLDSTATE.luciferDefeated && WORLDSTATE.gehFinaleWitnessed && AFTERLIFE.phase === 'release', 'the completed hold begins a participant release scene');
    check(e.alive && e.mesh.visible && !e.armed && e.noBar && !EXTRA.includes(e), 'Lucifer survives outside the combat and corpse paths');
    check(P.hp === health && P.pos.equals(position) && heroLevel() === level && P.kills === kills, 'surrender preserves player health, position, skills and kill count');
    const members = GEH.netFinale.members.slice(); gehLuciferDown();
    check(GEH.netFinale.t === 0 && GEH.netFinale.members.join() === members.join(), 'duplicate surrender does not restart or change the participant set');
    updateAfterlife(3.1);
    check(!GEH.prideShelter && e.mesh.visible && hero.scale.y === 1 && e.luciferRig.arms.every(a => a.palm.position.y < 2), 'Lucifer lowers open hands without flattening either character');
    updateAfterlife(5);
    check(GEH.prideChildren[0].position.x < GEH.prideChildren[0].userData.home.x - 10 && !GEH.godHand.visible, 'a child heads for the bridge while the hand withdraws');
    updateAfterlife(10);
    check(AFTERLIFE.phase === 'credits' && e.alive && e.bodyScale === 0.62 && GEH.prideChildren.every(c => c.visible), 'children remain in the world when the living Lucifer reaches credits');
    check(GEH.prideChildren[0].position.x < GEH.cx - 96 && GEH.prideChildren[1].scale.y === 0.72 && GEH.prideChildren[2].position.z === GEH.cz + 64, 'the children independently cross, rest and explore without automatic ascension');
