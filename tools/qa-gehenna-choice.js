    answerChoice(1); showModernEnding(2);
    check(WORLDSTATE.afterlife === 'moveOn' && AFTERLIFE.phase === 'modern' && /By the river/.test(AFTERLIFE.panel.textContent) && !/Ysolde|reborn/.test(AFTERLIFE.panel.textContent), 'Move on preserves the modern story and its unspoken absence');
